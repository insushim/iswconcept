// 모든 수학 성취기준
export const ALL_MATH_STANDARDS: AchievementStandard[] = [
  ...MATH_STANDARDS_1_2,
  ...MATH_STANDARDS_3_4,
  ...MATH_STANDARDS_5_6,
];

// 학년군별 성취기준 조회
export const getMathStandardsByGradeGroup = (gradeGroup: '1-2' | '3-4' | '5-6'): AchievementStandard[] => {
  switch (gradeGroup) {
    case '1-2': return MATH_STANDARDS_1_2;
    case '3-4': return MATH_STANDARDS_3_4;
    case '5-6': return MATH_STANDARDS_5_6;
  }
};

// 영역별 성취기준 조회
export const getMathStandardsByDomain = (domain: string): AchievementStandard[] => {
  return ALL_MATH_STANDARDS.filter(s => s.domain === domain);
};

// 코드로 성취기준 조회
export const getMathStandardByCode = (code: string): AchievementStandard | undefined => {
  return ALL_MATH_STANDARDS.find(s => s.code === code);
};
