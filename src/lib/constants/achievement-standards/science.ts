// 모든 과학 성취기준
export const ALL_SCIENCE_STANDARDS: AchievementStandard[] = [
  ...SCIENCE_STANDARDS_3_4,
  ...SCIENCE_STANDARDS_5_6,
];

// 학년군별 성취기준 조회
export const getScienceStandardsByGradeGroup = (gradeGroup: '3-4' | '5-6'): AchievementStandard[] => {
  switch (gradeGroup) {
    case '3-4': return SCIENCE_STANDARDS_3_4;
    case '5-6': return SCIENCE_STANDARDS_5_6;
    default: return [];
  }
};

// 영역별 성취기준 조회
export const getScienceStandardsByDomain = (domain: string): AchievementStandard[] => {
  return ALL_SCIENCE_STANDARDS.filter(s => s.domain === domain);
};

// 코드로 성취기준 조회
export const getScienceStandardByCode = (code: string): AchievementStandard | undefined => {
  return ALL_SCIENCE_STANDARDS.find(s => s.code === code);
};
